"""Write the chosen bought parts into the CAD: requirements/selection.toml -> cad/pod/bought.py.

    python3 tools/partsel/to_cad.py            # write cad/pod/bought.py
    python3 tools/partsel/to_cad.py --check    # exit 1 if bought.py is out of date

Each [role] in selection.toml names a requirements file and a part card. The card's values (as printed by
the vendor, with their sources) become one dict per role in bought.py, so the STEVE components read sizes
and masses from there and every number traces back to a card. The selector must pass the part, or the
selection must say why not (status "provisional").
"""
import argparse
import sys
import tomllib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import partsel  # noqa: E402

ROOT = partsel.ROOT
SELECTION = ROOT / "requirements" / "selection.toml"
OUT = ROOT / "cad" / "pod" / "bought.py"


def build():
    with SELECTION.open("rb") as f:
        selection = tomllib.load(f)
    lines = [
        '"""Bought parts in the pod. Generated by tools/partsel/to_cad.py from requirements/selection.toml:',
        "do not edit by hand. Values are as the vendor prints them; each part's card in parts/ cites the source.",
        '"""',
        "",
    ]
    for role, pick in selection.items():
        with (ROOT / "requirements" / pick["requirement"]).open("rb") as f:
            req = tomllib.load(f)
        cards = {c["id"]: c for c in partsel.load_cards(req["category"])}
        if pick["part"] not in cards:
            sys.exit(f"{role}: no card {pick['part']} in parts/{req['category']}/")
        card = cards[pick["part"]]
        verdict = next(r["verdict"] for r in partsel.evaluate(req) if r["id"] == pick["part"])
        if verdict == "FAIL" and pick.get("status") != "provisional":
            sys.exit(f"{role}: {pick['part']} fails {pick['requirement']}; mark it provisional with a reason")
        values = {k: partsel.value(card, k) for k in card.get("values", {})}
        entry = {"id": card["id"], "maker": card["maker"], "model": card["model"], "status": pick.get("status", ""),
                 "verdict": verdict, "card": card["_file"], **values}
        lines.append(f"# {role}: {card['maker']} {card['model']} ({pick.get('status', '')}, selector {verdict})")
        lines.append(f"{role.upper()} = {{")
        for key, v in entry.items():
            lines.append(f"    {key!r}: {v!r},")
        lines.append("}")
        lines.append("")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if bought.py differs from the selection")
    args = ap.parse_args()
    text = build()
    if args.check:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run tools/partsel/to_cad.py")
            return 1
        print("bought.py is up to date")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} ({text.count(' = {')} parts)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
